<p><b>After:</b> "A buyer would likely value the business at $6 to $8 million today. That is well above the roughly $3.7 million you need to retire comfortably, which gives you room to choose the path you prefer. The value is held back mainly by how much depends on you personally. The appendix shows how we got there."</p>
