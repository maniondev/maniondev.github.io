#!/usr/bin/env node
// Stamps values from site.config.json into the wedding pages.
//
//   node build.mjs           update the pages and assets/config.js in place
//   node build.mjs --check   change nothing; exit 1 if a page is out of date
//                            or links with a root-relative or hardcoded URL
//
// Pages link to each other and to assets with relative URLs, so the same
// files work under /wedding/ or at the root of their own domain. Only values
// that must be absolute (canonical and Open Graph URLs) or that come from
// config (contact email) are written into the HTML, between
// <!-- build:NAME --> and <!-- /build:NAME --> markers. Runtime values for
// scripts go to assets/config.js. No dependencies; needs Node 18 or newer.

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
const config = JSON.parse(readFileSync(join(root, "site.config.json"), "utf8"));

const siteUrl = config.siteUrl.replace(/\/+$/, "");
// "/wedding" today, "" once the site lives at the root of its own domain.
const basePath = new URL(siteUrl).pathname.replace(/\/+$/, "");

// Folders that hold tooling or docs, not pages.
const SKIP_DIRS = new Set(["apps-script", "tools", "node_modules"]);
const CONFIG_JS = join("assets", "config.js");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".")) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (!SKIP_DIRS.has(name)) walk(full, out);
    } else {
      out.push(relative(root, full));
    }
  }
  return out;
}

function escapeHtml(s) {
  return String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// Absolute URL of a page: "rsvp/index.html" -> "<siteUrl>/rsvp/".
function pageUrl(rel) {
  const dir = rel.split(sep).slice(0, -1).join("/");
  return `${siteUrl}/${dir ? dir + "/" : ""}`;
}

// Each region returns its new contents. Block regions sit on their own lines.
const REGIONS = {
  head: {
    block: true,
    render: (rel) => {
      const url = pageUrl(rel);
      const image = `${siteUrl}/og-image.png`;
      return [
        `<link rel="canonical" href="${url}">`,
        `<meta property="og:url" content="${url}">`,
        `<meta property="og:image" content="${image}">`,
        `<meta name="twitter:image" content="${image}">`,
      ].join("\n");
    },
  },
  contact: {
    block: false,
    render: () =>
      config.contactEmail
        ? `<a href="mailto:${escapeHtml(config.contactEmail)}">${escapeHtml(config.contactEmail)}</a>`
        : `<span class="tbd">[TBD] contact email</span>`,
  },
};

const REGION_RE = /<!-- build:([\w-]+) -->([\s\S]*?)<!-- \/build:\1 -->/g;

function stamp(html, rel, problems) {
  return html.replace(REGION_RE, (whole, name) => {
    const region = REGIONS[name];
    if (!region) {
      problems.push(`${rel}: unknown build region "${name}"`);
      return whole;
    }
    const body = region.render(rel);
    return region.block
      ? `<!-- build:${name} -->\n${body}\n<!-- /build:${name} -->`
      : `<!-- build:${name} -->${body}<!-- /build:${name} -->`;
  });
}

function renderConfigJs() {
  const runtime = {
    siteUrl,
    basePath,
    weddingDate: config.weddingDate,
    ceremonyStart: config.ceremonyStart,
    contactEmail: config.contactEmail,
    rsvpEndpoint: config.rsvpEndpoint,
    rsvpDeadline: config.rsvpDeadline,
  };
  return (
    "// Generated by build.mjs from site.config.json. Edit that file, then run: node build.mjs\n" +
    `window.WEDDING_CONFIG = ${JSON.stringify(runtime, null, 2)};\n`
  );
}

// Links that would break when the base path changes.
function findHardcodedUrls(text, rel, problems) {
  const stripped = text.replace(REGION_RE, "");
  const patterns = [
    [/\b(?:href|src|action|poster)\s*=\s*["']\/(?!\/)/g, "root-relative URL"],
    [/\burl\(\s*["']?\/(?!\/)/g, "root-relative url()"],
  ];
  if (basePath) patterns.push([new RegExp(`["'(]${basePath}/`, "g"), `hardcoded base path ${basePath}/`]);
  for (const [re, label] of patterns) {
    for (const m of stripped.matchAll(re)) {
      const line = stripped.slice(0, m.index).split("\n").length;
      problems.push(`${rel}:${line}: ${label}`);
    }
  }
  if (stripped.includes(siteUrl)) problems.push(`${rel}: contains the site URL outside a build region`);
}

const problems = [];
const stale = [];
const files = walk(root);

for (const rel of files) {
  if (rel === CONFIG_JS) continue;
  if (/\.(html|css|js)$/.test(rel)) findHardcodedUrls(readFileSync(join(root, rel), "utf8"), rel, problems);
  if (!rel.endsWith(".html")) continue;
  const path = join(root, rel);
  const before = readFileSync(path, "utf8");
  const after = stamp(before, rel, problems);
  if (after !== before) {
    stale.push(rel);
    if (!check) writeFileSync(path, after);
  }
}

const configPath = join(root, CONFIG_JS);
const configJs = renderConfigJs();
let currentConfigJs = "";
try { currentConfigJs = readFileSync(configPath, "utf8"); } catch {}
if (currentConfigJs !== configJs) {
  stale.push(CONFIG_JS);
  if (!check) writeFileSync(configPath, configJs);
}

for (const p of problems) console.error(`problem: ${p}`);
if (check) {
  for (const s of stale) console.error(`out of date: ${s} (run node build.mjs)`);
  if (problems.length || stale.length) process.exit(1);
  console.log(`OK: ${files.length} files checked against ${siteUrl}`);
} else {
  console.log(stale.length ? `Updated: ${stale.join(", ")}` : "Already up to date.");
  if (problems.length) process.exit(1);
}
